export async function getLanguage() {
  // English-only for now. (Multi-language support may return later; the German
  // dictionary is kept as a fallback but is no longer user-selectable.)
  return "en";
}

export async function setLanguage(_lang) {
  await chrome.storage.local.set({ language: "en" });
}

export function t(lang, key, ...args) {
  const dict = STRINGS.en || STRINGS.de;
  const value = dict[key] ?? STRINGS.en[key] ?? STRINGS.de[key] ?? key;
  return typeof value === "function" ? value(...args) : value;
}
